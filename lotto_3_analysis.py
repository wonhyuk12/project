import csv, math, os

# ==================================================================
# 로또 특정 번호 '3'(03) 분석기  (실제 데이터 기반)
#
#   질문: "번호 3이 어느 회차에 나올까? 미래를 예측할 수 있나?"
#
#   데이터: 동행복권 로또 6/45 실제 당첨번호
#           1049회(2023-01-07) ~ 1231회(2026-07-04), 총 183회차
#           (smok95.github.io/lotto 에서 수집 → lotto_2023_2026.csv)
#
#   이 코드가 하는 일:
#     ① 번호 3이 실제로 회차마다 얼마나 나왔는지 집계
#     ② 이론상 확률(무작위 가정)과 비교
#     ③ '무작위인지'를 3가지 통계 검정으로 확인
#        → 무작위라면 "다음에 언제 나올지" 예측은 원리적으로 불가능함을 증명
#     ④ 정직한 미래 확률 제시
# ==================================================================

TARGET = 3   # ← 분석할 번호. 다른 번호(예: 7, 33)가 궁금하면 이 값만 바꾸면 됨

# 어느 폴더에서 실행하든 CSV를 찾도록, '이 스크립트가 있는 폴더' 기준으로 경로 지정
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(SCRIPT_DIR, "lotto_2023_2026.csv")

# ------------------------------------------------------------------
# 1) 실제 데이터 로드
# ------------------------------------------------------------------
if not os.path.exists(CSV_PATH):
    raise SystemExit(f"[에러] {CSV_PATH}\n  → CSV를 이 스크립트와 같은 폴더에 두세요.")

draws = []   # 각 원소: (회차, 날짜, [번호6개])
with open(CSV_PATH, newline="", encoding="utf-8") as f:
    for row in csv.DictReader(f):
        nums = [int(row[f"n{i}"]) for i in range(1, 7)]
        draws.append((int(row["round"]), row["date"], nums))
draws.sort()
N = len(draws)

print("=" * 64)
print(f"로또 번호 '{TARGET}'({TARGET:02d}) 분석  (실제 데이터)")
print("=" * 64)
print(f"대상 : {draws[0][0]}회({draws[0][1]}) ~ {draws[-1][0]}회({draws[-1][1]}), 총 {N}회차")

# ------------------------------------------------------------------
# 2) 회차별 집계 : 이번 회차에 번호 3이 나왔나?
#    특정 번호 1개라, 한 회차에 나오면 1 / 안 나오면 0 (0 또는 1)
# ------------------------------------------------------------------
hit = [1 if TARGET in nums else 0 for _, _, nums in draws]   # 회차별 출현 여부
n_hit = sum(hit)
hit_rounds = [draws[i][0] for i in range(N) if hit[i]]       # 실제로 나온 회차 목록

print(f"\n[집계] 번호 {TARGET}이(가) 나온 회차 : {n_hit}회 / {N}회 "
      f"= {n_hit/N*100:.1f}%")
print(f"       나온 회차 번호들 : {hit_rounds}")

# ------------------------------------------------------------------
# 3) 이론 확률(완전 무작위 가정)과 비교
#    45개 중 6개를 뽑으니, 특정 번호 1개가 뽑힐 확률 = 6/45
# ------------------------------------------------------------------
p = 6 / 45                       # 한 회차에 번호 3이 나올 이론 확률 ≈ 13.33%
exp_hits = p * N                 # 183회차 동안 기대 출현 횟수
sd = math.sqrt(N * p * (1 - p))  # 표준편차 (얼마나 흔들릴 수 있나)
print(f"\n[이론] 한 회차에 번호 {TARGET}이 나올 확률 = 6/45 = {p*100:.2f}%")
print(f"       {N}회차 기대 출현 = {exp_hits:.1f}회  (실제 {n_hit}회)")

# ------------------------------------------------------------------
# 4) 무작위성 검정 ①  출현 횟수가 정상 범위인가 (이항분포 z-검정)
# ------------------------------------------------------------------
z = (n_hit - exp_hits) / sd
print("\n[검정①] 출현 횟수가 우연 범위 안인가 (z-점수)")
print(f"  z = ({n_hit} - {exp_hits:.1f}) / {sd:.2f} = {z:+.2f}")
if abs(z) < 2:
    print("  → |z|<2 = 완전 무작위로 기대되는 정상 범위. 이상 징후 없음.")
else:
    print("  → |z|>=2 = 다소 벗어남. 하지만 회차가 적으면 우연히도 이 정도는 나옴.")

# ------------------------------------------------------------------
# 5) 무작위성 검정 ②  자기상관 (직전 회차가 다음 회차를 예측하나?)
# ------------------------------------------------------------------
after_hit  = [hit[i+1] for i in range(N-1) if hit[i] == 1]   # 나온 다음 회차
after_miss = [hit[i+1] for i in range(N-1) if hit[i] == 0]   # 안 나온 다음 회차
p_ah = sum(after_hit)/len(after_hit) if after_hit else 0
p_am = sum(after_miss)/len(after_miss) if after_miss else 0
print("\n[검정②] 자기상관 (직전 회차 결과가 다음에 영향?)")
print(f"  전체 평균 출현율                 : {n_hit/N*100:5.1f}%")
print(f"  '직전에 나왔을 때' 다음 회차 출현율 : {p_ah*100:5.1f}%")
print(f"  '직전에 안나왔을 때' 다음 회차 출현율: {p_am*100:5.1f}%")
print("  → 세 값이 비슷하면 = 직전 결과가 다음에 영향 없음(독립). 예측 불가.")

# ------------------------------------------------------------------
# 6) 무작위성 검정 ③  출현 간격 (도박사의 오류 점검)
#    "요즘 안 나왔으니 곧 나올 때가 됐다"가 통하는가?
# ------------------------------------------------------------------
gaps = [hit_rounds[i+1]-hit_rounds[i] for i in range(len(hit_rounds)-1)]
print("\n[검정③] 번호 3이 다시 나오기까지 걸린 간격")
if gaps:
    print(f"  간격들 : {gaps}")
    print(f"  평균 {sum(gaps)/len(gaps):.1f}회 (이론 기대값 1/p = {1/p:.1f}회), "
          f"최소 {min(gaps)}, 최대 {max(gaps)}")
    print("  → 간격이 제멋대로(기억 없음). '나올 때가 됐다'는 근거 없음 = 도박사의 오류.")

# ------------------------------------------------------------------
# 7) 정직한 결론 & 미래 확률
# ------------------------------------------------------------------
print("\n" + "=" * 64)
print("결론 & 미래 예측")
print("=" * 64)
last = draws[-1][0]
print(f"""
로또 추첨은 매 회차 '독립적인 무작위'입니다. 위 3가지 검정 모두
"과거로 다음 회차를 맞힐 규칙은 없다"를 실제 데이터로 확인해 줍니다.

따라서 '번호 {TARGET}이 몇 회차에 나올지'를 콕 집는 것은 불가능합니다.
할 수 있는 가장 정직한 답은 '확률'뿐입니다 (매주 동일·독립):

  ▶ 다가오는 아무 회차든 번호 {TARGET}이 나올 확률 = {p*100:.2f}%
  ▶ 평균적으로 약 {1/p:.1f}회(주)에 한 번꼴로 나옵니다.
""")
print("다음 회차별 출현 확률 (모두 동일·독립, 특정 불가):")
for r in range(last+1, last+6):
    print(f"  {r}회차 : 번호 {TARGET} 나올 확률 = {p*100:.2f}%")

print("\n'앞으로 n회차 안에 최소 1번' 나올 확률 (누적):")
for n_next in (1, 5, 10, 20):
    prob = (1 - (1 - p) ** n_next) * 100
    print(f"  다음 {n_next:2d}회차 안 : {prob:5.1f}%")
print("""
※ 여러 회차를 묶으면 '언젠가는' 나올 확률이 올라가지만,
   '정확히 어느 회차'인지는 원리적으로 알 수 없습니다. (무작위의 본질)
""")
