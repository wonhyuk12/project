# ===================================================================
# db.py  —  "Supabase 에 접속하는 클라이언트를 만들어 두는 곳"
# -------------------------------------------------------------------
# Supabase 클라이언트가 뭔가요?
#   - 파이썬 코드에서 Supabase(데이터베이스 · 사진저장소 · 로그인)를
#     다루게 해주는 '리모컨' 같은 객체예요.
#
# 왜 service key 를 쓰나요?
#   - 우리 DB 는 RLS(행 수준 보안)가 켜져 있고 정책이 없어서,
#     일반 키로는 아무 데이터도 못 봅니다.
#   - 백엔드는 'service key'(관리자 키)로 접속해 RLS 를 통과합니다.
#   - 대신! service key 는 모든 가게 데이터에 접근 가능하므로,
#     "코드에서 반드시 shop_id 로 걸러주는" 책임이 우리에게 있어요.
#     (그 강제 장치는 다음 파일 security.py 에서 만듭니다.)
#
# ※ service key 는 절대 프론트(브라우저)로 내려보내면 안 됩니다. 서버 안에서만!
# ===================================================================

from supabase import create_client, Client

from backend.config import settings  # 우리가 만든 설정 상자에서 값을 가져옴


# -------------------------------------------------------------------
# 백엔드 전용 Supabase 클라이언트 (service key 사용)
#   - 프로그램 전체에서 이 하나를 공유해서 씁니다.
#   - DB 조회/저장, 사진 업로드, signed URL 만들기 등에 사용해요.
# -------------------------------------------------------------------
supabase: Client = create_client(
    settings.SUPABASE_URL,          # 프로젝트 주소
    settings.SUPABASE_SERVICE_KEY,  # 관리자 키 (RLS 통과용, 서버 전용)
)
