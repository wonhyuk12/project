export function getTourById(id) {
  return tours.find((tour) => tour.id === id);
}

export function getDisplayPrice(tour) {
  if (tour.tiers) {
    const premium = tour.tiers.find((t) => t.id === 'premium');
    return premium ? premium.price : tour.tiers[0].price;
  }
  return tour.price;
}

export function formatPrice(price) {
  return price == null ? '[가격 문의]' : `₩${price.toLocaleString()}`;
}
